#!/usr/bin/env bash
# Writes the PKGBUILD and .SRCINFO for a released version into a directory.
#
# Usage: VERSION=1.2.3 packaging/aur/render.sh OUT
#
# The checksum is taken from the release's source tarball on GitHub, so the
# tag must already exist and the repository must be public. Set SHA256 to
# skip the download, and CONTAINER=podman to use podman instead of docker.
# OUT must not exist yet.
set -euo pipefail

out="${1:?usage: render.sh OUT}"
: "${VERSION:?VERSION is not set}"
container="${CONTAINER:-docker}"

here="$(cd "$(dirname "$0")" && pwd)"
url="https://github.com/omorfos/desktop/archive/refs/tags/v${VERSION}.tar.gz"
sha256="${SHA256:-$(curl -sSfL "${url}" | sha256sum | cut -d' ' -f1)}"

mkdir "${out}"
sed \
  -e "s/^pkgver=.*/pkgver=${VERSION}/" \
  -e "s/^pkgrel=.*/pkgrel=1/" \
  -e "s/^sha256sums=.*/sha256sums=('${sha256}')/" \
  "${here}/PKGBUILD" > "${out}/PKGBUILD"

# .SRCINFO must be generated by makepkg, which only exists on Arch, refuses
# to run as root, and wants a writable directory even for this. So the
# PKGBUILD is copied to an unprivileged user's home inside the container.
"${container}" run --rm -v "$(cd "${out}" && pwd):/pkg:ro" docker.io/library/archlinux:base-devel \
  bash -c 'useradd -m build >/dev/null && install -o build /pkg/PKGBUILD /home/build/ \
    && su build -c "cd && makepkg --printsrcinfo"'  \
  > "${out}/.SRCINFO"

cat "${out}/.SRCINFO"
